#!/usr/bin/env python3
"""Generate a deterministic synthetic image dataset.

The dataset is generated rather than downloaded, so that every learner measures
the same data and no large files enter Git.

    # Built-in profile, straight to a directory
    python scripts/generate_dataset.py --profile tiny --output /tmp/daai-test

    # Profile from a configuration file, parallel encoding
    python scripts/generate_dataset.py \\
        --profile-config configs/datasets/balanced.yaml \\
        --output "$TUTORIAL_ROOT/source" \\
        --manifest data/manifests/balanced.jsonl \\
        --workers 16
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from dataaware.generate import PROFILES, generate_dataset, load_profile  # noqa: E402
from dataaware.manifest import read_manifest, total_bytes  # noqa: E402


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument(
        "--profile",
        choices=sorted(PROFILES),
        help="built-in dataset profile",
    )
    source.add_argument(
        "--profile-config",
        type=Path,
        help="YAML file with a top-level 'dataset' mapping",
    )
    parser.add_argument(
        "--output", type=Path, required=True, help="directory to write the dataset into"
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=None,
        help="manifest path (default: <output>/manifest.jsonl)",
    )
    parser.add_argument(
        "--workers",
        type=int,
        default=1,
        help="processes used for encoding; does not affect the generated bytes",
    )
    parser.add_argument(
        "--seed", type=int, default=None, help="override the profile seed"
    )
    parser.add_argument(
        "--samples", type=int, default=None, help="override the profile sample count"
    )
    parser.add_argument(
        "--overwrite", action="store_true", help="regenerate into a non-empty directory"
    )
    args = parser.parse_args(argv)

    profile = (
        PROFILES[args.profile]
        if args.profile
        else load_profile(args.profile_config)
    )
    replacements = {}
    if args.seed is not None:
        replacements["seed"] = args.seed
    if args.samples is not None:
        replacements["samples"] = args.samples
    if replacements:
        from dataclasses import replace

        profile = replace(profile, **replacements)
        profile.validate("command line override")

    if args.workers < 1:
        parser.error("--workers must be >= 1")

    manifest_path = generate_dataset(
        profile=profile,
        output_dir=args.output,
        manifest_path=args.manifest,
        workers=args.workers,
        overwrite=args.overwrite,
        progress_every=max(1, profile.samples // 10),
    )

    samples = read_manifest(manifest_path)
    print("DATASET_PROFILE=" + profile.profile)
    print(f"DATASET_PATH={args.output}")
    print(f"MANIFEST_PATH={manifest_path}")
    print(f"TOTAL_SAMPLES={len(samples)}")
    print(f"TOTAL_BYTES={total_bytes(samples)}")
    print(f"MEAN_FILE_BYTES={total_bytes(samples) // max(1, len(samples))}")
    print(f"SEED={profile.seed}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
